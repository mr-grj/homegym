const known: Partial<Record<MoveId, Hint>> = HINTS

const hintFor = (label: string) => {
  const id = moveFor(label)?.id
  return id ? known[id] : undefined
}

/** The technique cue for this moment, or null: how to set up while the next exercise is previewed, armed or in its prep, how to move while it runs. A note on the current exercise takes its place. */
export function hintNow(run: Run, now: number): string | null {
  const shown = demoStep(run)
  const hint = shown && hintFor(shown.label)
  const step = run.steps[run.index]
  if (!hint || (!step.rest && step.note)) return null
  return (step.rest || !run.startedAt || preparing(run, now) ? hint.setup : hint.form) ?? null
}

/** True when some exercise has a technique cue, so the stage keeps a line for it. */
export const hasHints = (steps: Step[]) => steps.some((s) => !s.rest && !!hintFor(s.label))
