import { addRoutine, expect, recorded, shortcut, test } from './fixtures'

const WORK = [660, 990]
const READY = [660]
const TICK = [880]

test('each exercise opens with a countdown to get into position', async ({ app }) => {
  await app.locator('.chip-main', { hasText: 'Full body' }).click()
  const time = app.locator('.time')
  const label = app.locator('.label')
  const cue = app.locator('.prep-cue')
  await expect(time).toHaveText('0:30')
  await expect(cue).toHaveCount(0)
  await expect(app.locator('.meta')).toContainText('/ 26:35')

  await shortcut(app, 'Space')
  await expect(cue).toHaveText('Get into position')
  await expect(label).toHaveText('Cat-cow')
  await expect(time).toHaveText('5')
  await expect(app).toHaveTitle('▶ 5 · Cat-cow')
  await app.clock.runFor(2000)
  await expect(time).toHaveText('3')
  await expect(app.locator('.time.urgent')).toBeVisible()
  await app.clock.runFor(2000)
  await expect(time).toHaveText('1')
  await app.clock.runFor(1000)
  await expect(time).toHaveText('0:30')
  await expect(cue).toHaveCount(0)
  await app.clock.runFor(400)
  expect(await recorded(app)).toMatchObject({ tones: [...READY, ...TICK, ...TICK, ...TICK, ...WORK], speech: ['Cat-cow'] })

  await shortcut(app, 'ArrowRight')
  await expect(label).toHaveText('Bodyweight squats')
  await expect(time).toHaveText('5')
  await shortcut(app, 'ArrowRight')
  await expect(label).toHaveText('Hip hinges, flat back')
  await cue.click()
  await expect(time).toHaveText('0:30')
  await expect(cue).toHaveCount(0)
  await expect(app.locator('.stage')).toHaveAttribute('data-state', 'running')
  await shortcut(app, 'ArrowRight')
  await expect(cue).toBeVisible()
  await shortcut(app, 'g')
  await expect(time).toHaveText('0:30')
  expect((await recorded(app)).tones.slice(-2)).toEqual(WORK)

  await shortcut(app, 'r')
  await expect(app.locator('.toast')).toContainText('Get into position time off')
  await expect(app.locator('.meta')).toContainText('/ 24:15')
  await shortcut(app, 'ArrowRight')
  await expect(label).toHaveText('Inchworms')
  await expect(time).toHaveText('0:30')
  await expect(cue).toHaveCount(0)

  await shortcut(app, 'r')
  await expect(app.locator('.toast')).toContainText('Get into position time on')
  await shortcut(app, 'ArrowRight')
  await expect(label).toHaveText('Kettlebell swing')
  await shortcut(app, 'ArrowRight')
  await expect(label).toHaveText('Switch')
  const heard = (await recorded(app)).tones.length
  await app.clock.runFor(15_100)
  await expect(label).toHaveText('Push-ups')
  await expect(time).toHaveText('5')
  expect((await recorded(app)).tones.slice(heard)).toEqual(READY)
})

test('every rest shows a glass of water above the next exercise, one sip at a time', async ({ app }) => {
  await app.locator('.chip-main', { hasText: 'Full body' }).click()
  await shortcut(app, 'Space')
  const time = app.locator('.time')
  const label = app.locator('.label')
  const water = app.locator('.water')

  await app.locator('.tl-step').nth(6).click()
  await expect(label).toHaveText('Switch')
  await expect(app.locator('.demo-over .demo-cue')).toHaveText('Up next')
  await expect(app.locator('.demo-over .water')).toHaveText('Sip some water')
  await expect(app.locator('.cue .water')).toHaveCount(0)

  await app.locator('.tl-step').nth(8).click()
  await expect(label).toHaveText('Rest')
  await app.clock.runFor(2000)
  await expect(time).toHaveText('0:38')

  await water.click()
  await expect(time).toHaveText('0:53')
  await expect(water).toHaveText(/Drinking/)
  await expect(water).toHaveAttribute('aria-disabled', 'true')
  await expect(water.locator('.sip')).toHaveText('+15s')
  await water.click({ force: true })
  await shortcut(app, 'w')
  await expect(time).toHaveText('0:53')

  await shortcut(app, 'Space')
  await expect(water).toHaveAttribute('data-hidden')
  await expect(app.locator('.cue')).toContainText('Paused')
  await app.clock.runFor(20_000)
  await shortcut(app, 'Space')
  await expect(water).not.toHaveAttribute('data-hidden')
  await expect(water).toHaveText(/Drinking/)

  await app.clock.runFor(15_000)
  await expect(water).toHaveText('Sip some water')
  await expect(water).not.toHaveAttribute('aria-disabled')
  await shortcut(app, 'w')
  await expect(time).toHaveText('0:53')
  await expect(app.locator('.stage')).toHaveAttribute('data-state', 'running')

  await shortcut(app, 'ArrowRight')
  await expect(label).toHaveText('Kettlebell swing')
  await expect(water).toHaveCount(0)
  await shortcut(app, 'w')
  await shortcut(app, 'g')
  await expect(time).toHaveText('0:40')
})

