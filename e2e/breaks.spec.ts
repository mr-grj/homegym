test('the workout options switch off prep time, the water glass and demos', async ({ app }) => {
  await app.locator('[data-tool=options]').click()
  const options = app.locator('.options')
  await expect(options.locator('h2')).toHaveText('Workout')
  for (const key of ['prep', 'water', 'demos']) {
    const box = options.locator(`[data-option=${key}] input`)
    await expect(box).toBeChecked()
    await box.uncheck()
  }
  await shortcut(app, 'Escape')

  await app.locator('.chip-main', { hasText: 'Full body' }).click()
  await expect(app.locator('.demo')).toHaveCount(0)
  await shortcut(app, 'Space')
  await expect(app.locator('.prep-cue')).toHaveCount(0)
  await expect(app.locator('.time')).toHaveText('0:30')
  await expect(app.locator('.meta')).toContainText('/ 24:15')

  await app.locator('.tl-step').nth(8).click()
  await expect(app.locator('.label')).toHaveText('Rest')
  await app.clock.runFor(3400)
  await expect(app.locator('.water')).toHaveCount(0)
  await shortcut(app, 'w')
  await expect(app.locator('.time')).toHaveText('0:37')

  await shortcut(app, 'o')
  await options.locator('[data-option=water] input').check()
  await shortcut(app, 'Escape')
  await expect(app.locator('.water')).toBeVisible()
  await app.reload()
  await shortcut(app, 'o')
  await expect(options.locator('[data-option=prep] input')).not.toBeChecked()
  await expect(options.locator('[data-option=water] input')).toBeChecked()
})
